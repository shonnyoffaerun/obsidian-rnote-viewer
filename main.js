var RnotePlugin = class extends import_obsidian2.Plugin {
  settings = DEFAULT_SETTINGS;
  cache;
  async onload() {
    await this.loadSettings();
    this.cache = new LruCache(this.settings.cacheCapacity);
    this.registerView(
      VIEW_TYPE_RNOTE,
      (leaf) => new RnoteView(leaf, this)
    );
    this.registerExtensions(["rnote"], VIEW_TYPE_RNOTE);
    this.registerMarkdownPostProcessor(async (el, ctx) => {
      await this.processMarkdownEmbeds(el, ctx.sourcePath);
    });
    this.registerMarkdownCodeBlockProcessor("rnote", async (source, el, ctx) => {
      await this.processCodeBlock(source, el, ctx.sourcePath);
    });
    this.addSettingTab(new RnoteSettingTab(this.app, this));
  }
  onunload() {
    this.cache.clear();
  }
  async loadSettings() {
    this.settings = Object.assign({}, DEFAULT_SETTINGS, await this.loadData());
  }
  async saveSettings() {
    await this.saveData(this.settings);
    if (this.cache) {
      this.cache.setCapacity(this.settings.cacheCapacity);
    }
  }
  /**
   * Resolves a file linkpath to a TFile in the vault, with fallbacks if metadataCache hasn't indexed it.
   */
  resolveRnoteFile(linkPath, sourcePath) {
    const fromCache = this.app.metadataCache.getFirstLinkpathDest(linkPath, sourcePath);
    if (fromCache instanceof import_obsidian2.TFile) return fromCache;
    const byPath = this.app.vault.getAbstractFileByPath(linkPath);
    if (byPath instanceof import_obsidian2.TFile) return byPath;
    const cleanTarget = linkPath.split("/").pop()?.trim().toLowerCase();
    const allFiles = this.app.vault.getFiles();
    const found = allFiles.find((f) => {
      if (f.extension !== "rnote") return false;
      const fPath = f.path.toLowerCase();
      const fName = f.name.toLowerCase();
      return fPath === linkPath.toLowerCase() || fName === cleanTarget || f.basename.toLowerCase() === cleanTarget;
    });
    return found ?? null;
  }
  /**
   * Processes all .rnote embeds found inside a rendered Markdown document.
   */
  async processMarkdownEmbeds(el, sourcePath) {
    const candidates = Array.from(
      el.querySelectorAll(
        '.internal-embed, .file-embed, [src*=".rnote"], [data-src*=".rnote"], [data-href*=".rnote"], [alt*=".rnote"], img[src*=".rnote"]'
      )
    );
    for (const target of candidates) {
      if (target.hasClass("rnote-embed-wrapper") || target.closest(".rnote-embed-wrapper")) {
        continue;
      }
      const rawSrc = target.getAttribute("src") || target.getAttribute("data-src") || target.getAttribute("data-href") || target.getAttribute("alt") || "";
      if (!rawSrc.toLowerCase().includes(".rnote")) continue;
      let linkPath = rawSrc.trim();
      let customWidth = null;
      if (linkPath.includes("|")) {
        const parts = linkPath.split("|");
        linkPath = parts[0].trim();
        const widthCandidate = parts[1].trim();
        if (/^\d+(x\d+)?$/.test(widthCandidate)) {
          customWidth = widthCandidate.includes("x") ? widthCandidate.split("x")[0] : widthCandidate;
        }
      }
      const alt = target.getAttribute("alt")?.trim();
      if (!customWidth && alt && /^\d+$/.test(alt)) {
        customWidth = alt;
      }
      const file = this.resolveRnoteFile(linkPath, sourcePath);
      if (!(file instanceof import_obsidian2.TFile)) continue;
      await this.renderEmbedElement(target, file, customWidth, false);
    }
  }
  /**
   * Processes ```rnote code blocks
   */
  async processCodeBlock(source, containerEl, sourcePath) {
    const trimmed = source.trim();
    if (!trimmed) return;
    const firstLine = trimmed.split("\n")[0].trim();
    let linkPath = firstLine;
    let customWidth = null;
    if (linkPath.includes("|")) {
      const parts = linkPath.split("|");
      linkPath = parts[0].trim();
      customWidth = parts[1].trim();
    }
    const file = this.resolveRnoteFile(linkPath, sourcePath);
    if (!file) {
      containerEl.empty();
      const errBox = containerEl.createDiv({ cls: "rnote-error-container" });
      errBox.createDiv({ cls: "rnote-error-title", text: `Rnote drawing not found: ${linkPath}` });
      return;
    }
    await this.renderEmbedElement(containerEl, file, customWidth, true);
  }
  /**
   * Renders the vector drawing directly inline inside Markdown notes.
   */
  async renderEmbedElement(targetEl, file, customWidth, isCodeBlock) {
    const scale = this.settings.strokeWidthScale ?? 0.45;
    const cacheKey = `${file.path}:${file.stat.mtime}:${this.settings.backgroundMode}:${scale}`;
    let cached = this.cache.get(cacheKey);
    const isDark = document.body.classList.contains("theme-dark");
    try {
      if (!cached) {
        const binary = await this.app.vault.readBinary(file);
        const parsed = await parseRnoteFile(binary);
        const rendered = renderRnoteToSvg(parsed, {
          backgroundMode: this.settings.backgroundMode,
          isDarkTheme: isDark,
          strokeWidthScale: scale
        });
        cached = {
          svg: rendered.svg,
          viewBox: rendered.viewBox,
          width: rendered.width,
          height: rendered.height
        };
        this.cache.set(cacheKey, cached);
      }
      const wrapper = isCodeBlock ? targetEl : createDiv({ cls: "rnote-embed-wrapper" });
      if (isCodeBlock) {
        wrapper.empty();
        wrapper.addClass("rnote-embed-wrapper");
      }
      if (customWidth) {
        wrapper.style.maxWidth = `${customWidth}px`;
      }
      const header = wrapper.createDiv({ cls: "rnote-embed-header" });
      const titleSpan = header.createSpan({ cls: "rnote-embed-title" });
      titleSpan.innerHTML = `\u270F\uFE0F <span>${file.basename}</span>`;
      titleSpan.addEventListener("click", (e) => {
        e.stopPropagation();
        this.app.workspace.getLeaf(false).openFile(file);
      });
      const openExternalBtn = header.createSpan({
        cls: "rnote-embed-action",
        text: "\u2197 Open in App",
        attr: { "aria-label": "Open in default Rnote app" }
      });
      openExternalBtn.addEventListener("click", (e) => {
        e.stopPropagation();
        const desktopApp = this.app;
        if (typeof desktopApp.openWithDefaultApp === "function") {
          desktopApp.openWithDefaultApp(file.path);
        }
      });
      const svgContainer = wrapper.createDiv({ cls: "rnote-embed-svg-container" });
      svgContainer.innerHTML = cached.svg;
      svgContainer.addEventListener("click", () => {
        this.app.workspace.getLeaf(false).openFile(file);
      });
      if (!isCodeBlock) {
        targetEl.replaceWith(wrapper);
      }
    } catch (err2) {
      console.error("[Rnote Viewer]", err2);
      const errBox = isCodeBlock ? targetEl : createDiv({ cls: "rnote-error-container" });
      if (isCodeBlock) errBox.empty();
      errBox.createDiv({ cls: "rnote-error-title", text: `Error loading ${file.basename}.rnote` });
      errBox.createDiv({
        cls: "rnote-error-message",
        text: err2 instanceof Error ? err2.message : String(err2)
      });
      if (!isCodeBlock) {
        targetEl.replaceWith(errBox);
      }
    }
  }
};
var RnoteSettingTab = class extends import_obsidian2.PluginSettingTab {
  plugin;
  constructor(app, plugin) {
    super(app, plugin);
    this.plugin = plugin;
  }
  display() {
    const { containerEl } = this;
    containerEl.empty();
    containerEl.createEl("h2", { text: "Rnote Viewer Settings" });
    new import_obsidian2.Setting(containerEl).setName("Background Mode").setDesc("Choose how the canvas background is rendered for .rnote files").addDropdown(
      (dropdown) => dropdown.addOption("adaptive", "Adaptive (Match Obsidian Theme)").addOption("rnote-native", "Rnote Native (Document colors & paper pattern)").addOption("transparent", "Transparent").addOption("light", "Always Light").addOption("dark", "Always Dark").setValue(this.plugin.settings.backgroundMode).onChange(async (value) => {
        this.plugin.settings.backgroundMode = value;
        this.plugin.cache.clear();
        await this.plugin.saveSettings();
      })
    );
    new import_obsidian2.Setting(containerEl).setName("Pen Stroke Thickness").setDesc("Calibrates stroke width so handwriting is fine, crisp, and authentic").addDropdown(
      (dropdown) => dropdown.addOption("0.45", "Fine (0.45x - Recommended for handwriting)").addOption("0.30", "Ultra-Fine (0.30x - Extra thin)").addOption("0.70", "Medium (0.70x)").addOption("1.00", "Original (1.00x - Native Rnote width)").setValue(String(this.plugin.settings.strokeWidthScale ?? 0.45)).onChange(async (value) => {
        this.plugin.settings.strokeWidthScale = parseFloat(value);
        this.plugin.cache.clear();
        await this.plugin.saveSettings();
      })
    );
    new import_obsidian2.Setting(containerEl).setName("Cache Capacity").setDesc("Maximum number of rendered SVG drawings to keep in memory for instant loading").addSlider(
      (slider) => slider.setLimits(20, 500, 10).setValue(this.plugin.settings.cacheCapacity).setDynamicTooltip().onChange(async (val) => {
        this.plugin.settings.cacheCapacity = val;
        await this.plugin.saveSettings();
      })
    );
    new import_obsidian2.Setting(containerEl).setName("Clear Render Cache").setDesc("Evict all in-memory SVG caches to reclaim memory").addButton(
      (btn) => btn.setButtonText("Clear Cache").onClick(() => {
        this.plugin.cache.clear();
        btn.setButtonText("Cleared!");
        setTimeout(() => btn.setButtonText("Clear Cache"), 2e3);
      })
    );
  }
};
