  /**
   * Starts smooth inertial physics decay loop (smartphone-like flick momentum).
   */
  startMomentum() {
    this.stopMomentum();
    const speed = Math.hypot(this.velocityX, this.velocityY);
    if (speed < 40) return;
    const maxSpeed = 7e3;
    if (speed > maxSpeed) {
      this.velocityX *= maxSpeed / speed;
      this.velocityY *= maxSpeed / speed;
    }
    let lastTime = performance.now();
    const friction = 0.93;
    const step = (now) => {
      const dt = Math.min(0.05, (now - lastTime) / 1e3);
      lastTime = now;
      this.currentViewMinX -= this.velocityX * dt;
      this.currentViewMinY -= this.velocityY * dt;
      const decay = Math.pow(friction, dt * 60);
      this.velocityX *= decay;
      this.velocityY *= decay;
      this.applyViewBox();
      if (Math.hypot(this.velocityX, this.velocityY) > 15) {
        this.momentumAnimId = requestAnimationFrame(step);
      } else {
        this.stopMomentum();
      }
    };
    this.momentumAnimId = requestAnimationFrame(step);
  }
  stopMomentum() {
    if (this.momentumAnimId !== null) {
      cancelAnimationFrame(this.momentumAnimId);
      this.momentumAnimId = null;
    }
    this.velocityX = 0;
    this.velocityY = 0;
  }
